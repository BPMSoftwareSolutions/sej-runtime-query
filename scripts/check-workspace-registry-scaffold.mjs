import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { spawnSync } from "node:child_process";

const root = process.cwd();
const manifest = readsJson(path.join(root, "architecture", "workspace-registry-capability-family.scaffold.v1.json"));
const bodyContract = readsJson(path.join(root, "architecture", "query-engine.body.contract.v1.json"));
const bodyEntries = new Map(bodyContract.capabilities.map((entry) => [entry.capabilityId, entry]));
const runtimeRegistry = fs.readFileSync(path.join(root, "composition-root", "creates-capability-registry.ts"), "utf8");
const failures = [];

if (manifest.capabilities.length !== 10) {
  failures.push(`workspace-registry family must contain 10 bounded capabilities; observed ${manifest.capabilities.length}`);
}

for (const capability of manifest.capabilities) {
  const id = capability.capabilityId;
  const capabilityRoot = path.join(root, "capabilities", id);
  const required = [
    "README.md",
    `intent/${id}.intent-ir.v1.json`,
    `features/${id}.feature`,
    `architecture/system-context.ascii.md`,
    `architecture/capability-boundary.ascii.md`,
    `architecture/semantic-execution-flow.ascii.md`,
    `architecture/proof-flow.ascii.md`,
    `contracts/${id}.input.schema.v1.json`,
    `contracts/${id}.execution-context.schema.v1.json`,
    `contracts/${id}.resolved-authority.schema.v1.json`,
    `contracts/${id}.result.schema.v1.json`,
    `contracts/${id}.receipt.schema.v1.json`,
    `1-semantic-authority/${id}.capability.sej.v1.json`,
    `1-semantic-authority/observations/${id}.observation.sej.v1.json`,
    `1-semantic-authority/decisions/${id}.decision.sej.v1.json`,
    `1-semantic-authority/policies/${id}.policy.sej.v1.json`,
    `1-semantic-authority/failure-policies/${id}.failure-policy.sej.v1.json`,
    `1-semantic-authority/state-models/${id}.state-model.sej.v1.json`,
    `1-semantic-authority/ports/${id}.port.sej.v1.json`,
    `1-semantic-authority/effects/${id}.effects.sej.v1.json`,
    `1-semantic-authority/proof-requirements/${id}.proof.requirement.sej.v1.json`,
    `2-semantic-projections/projects-${id}-result.sej.v1.json`,
    `2-semantic-projections/projects-${id}-receipt.sej.v1.json`,
    `3-semantic-execution-models/${id}.execution.sej.v1.json`,
    "projectors/typescript/capability-body.projection.v1.json",
    "projectors/typescript/projects-capability-body.ts",
    "projectors/typescript/projects-capability-types.ts",
    `runtime/typescript/bodies/${id}.ts`,
    `runtime/typescript/types/${id}-context.type.ts`,
    `runtime/typescript/registration/registers-${id}-authority.ts`,
    `conformance/${id}.conformance.v1.json`,
    `proof/fixtures/${id}.candidate.input.json`,
    `proof/expectations/${id}.candidate.expected.json`,
    `proof/canonicalization/${id}.canonicalization.v1.json`,
    `docs/${id}.md`,
    "governance/capability-body-policy.json",
    "governance/boundary-policy.json",
    "governance/promotion-policy.json",
  ];

  for (const relative of required) {
    if (!fs.existsSync(path.join(capabilityRoot, relative))) {
      failures.push(`${id} is missing ${relative}`);
    }
  }

  const authority = readsJson(path.join(capabilityRoot, "1-semantic-authority", `${id}.capability.sej.v1.json`));
  const vector = readsJson(path.join(capabilityRoot, "conformance", `${id}.conformance.v1.json`));
  const decision = readsJson(path.join(capabilityRoot, "1-semantic-authority", "decisions", `${id}.decision.sej.v1.json`));
  const resultProjection = readsJson(path.join(capabilityRoot, "2-semantic-projections", `projects-${id}-result.sej.v1.json`));
  const receiptProjection = readsJson(path.join(capabilityRoot, "2-semantic-projections", `projects-${id}-receipt.sej.v1.json`));
  const body = fs.readFileSync(path.join(capabilityRoot, "runtime", "typescript", "bodies", `${id}.ts`), "utf8");
  const adapters = listsFiles(path.join(capabilityRoot, "4-adapters")).filter((file) => file.endsWith(".ts"));

  if (authority.status !== "drafted" || authority.promotionDisposition !== "not-evaluated") {
    failures.push(`${id} must remain drafted and not-evaluated`);
  }
  if (bodyEntries.get(id)?.status !== "drafted") {
    failures.push(`${id} must be drafted in the file-system body contract`);
  }
  if (vector.status !== "candidate" || vector.kernelExecution !== "not-evaluated") {
    failures.push(`${id} candidate vector makes an unsupported execution claim`);
  }
  if (decision.rules.length !== 0) {
    failures.push(`${id} decision scaffold contains authored rules`);
  }
  if (resultProjection.expression !== null || receiptProjection.expression !== null) {
    failures.push(`${id} projection scaffold contains an authored expression`);
  }
  if (!body.startsWith("// @generated by scripts/project-linear-capability-bodies.mjs")) {
    failures.push(`${id} body does not carry generated provenance`);
  }
  if (adapters.length !== 0) {
    failures.push(`${id} seats TypeScript adapters before semantic implementation`);
  }
  if (runtimeRegistry.includes(`"${id}"`)) {
    failures.push(`${id} is drafted but appears in the live capability registry`);
  }

  const portCatalog = readsJson(path.join(capabilityRoot, "1-semantic-authority", "ports", `${id}.port.sej.v1.json`));
  for (const port of portCatalog.ports) {
    for (const direction of ["input", "output"]) {
      const contractPath = path.join(capabilityRoot, "contracts", "ports", `${port.portId}.${direction}.schema.v1.json`);
      if (!fs.existsSync(contractPath)) failures.push(`${id} is missing port contract ${path.relative(root, contractPath)}`);
    }
  }
}

const projectionCheck = spawnSync(
  process.execPath,
  ["scripts/project-linear-capability-bodies.mjs", "--check"],
  { cwd: root, encoding: "utf8" },
);
if (projectionCheck.status !== 0) {
  failures.push(projectionCheck.stderr || projectionCheck.stdout || "linear body projection check failed");
}

if (failures.length > 0) {
  console.error(failures.join("\n"));
  process.exitCode = 1;
} else {
  console.log(`PASS workspace-registry-scaffold (${manifest.capabilities.length} drafted bodies, projected-body parity verified)`);
}

function readsJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function listsFiles(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const candidate = path.join(directory, entry.name);
    return entry.isDirectory() ? listsFiles(candidate) : [candidate];
  });
}
