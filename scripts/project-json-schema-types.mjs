import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const checkOnly = process.argv.includes("--check");
const descriptorName = "json-schema-types.projection.v1.json";
const generatedMarker = "// @generated by scripts/project-json-schema-types.mjs";
const descriptors = walks(path.join(root, "capabilities"))
  .filter((file) => path.basename(file) === descriptorName)
  .sort();

for (const descriptorPath of descriptors) {
  projectsDescriptor(descriptorPath);
}

console.log(`PASS json-schema-type-projection (${descriptors.length} ${checkOnly ? "verified" : "projected"})`);

function projectsDescriptor(descriptorPath) {
  const descriptor = readsJson(descriptorPath);
  if (descriptor.projectionType !== "typescript-json-schema-types.v1") {
    throw new Error(`Unsupported type projection: ${path.relative(root, descriptorPath)}`);
  }
  if (!Array.isArray(descriptor.sources) || descriptor.sources.length === 0) {
    throw new Error(`Type projection must declare schema sources: ${path.relative(root, descriptorPath)}`);
  }

  const descriptorRoot = path.dirname(descriptorPath);
  const sources = descriptor.sources.map((source) => {
    const schemaPath = path.resolve(descriptorRoot, source.schema);
    const schema = readsJson(schemaPath);
    return { ...source, schemaPath, schema };
  });
  const namesByReference = indexesReferences(sources);
  const declarations = sources.flatMap((source) => source.declarations.map((declaration) => ({
    ...declaration,
    schemaPath: source.schemaPath,
    schema: source.schema,
    value: readsPointer(source.schema, declaration.pointer),
  })));
  const content = [
    generatedMarker,
    `// Sources: ${sources.map((source) => toPosix(path.relative(root, source.schemaPath))).join(", ")}`,
    'import type { JsonObject, JsonValue } from "@deterministic-solutions/semantic-kernel";',
    "",
    ...declarations.flatMap((declaration) => [
      rendersDeclaration(declaration.typeName, declaration.value, declaration.schema, namesByReference),
      "",
    ]),
  ].join("\n");

  projectsFile(path.resolve(descriptorRoot, descriptor.target), content);
}

function indexesReferences(sources) {
  const names = new Map();
  for (const source of sources) {
    for (const declaration of source.declarations) {
      const reference = declaration.pointer === "#"
        ? source.schema.$id
        : `${source.schema.$id}${declaration.pointer}`;
      if (typeof reference !== "string") {
        throw new Error(`Projected schema requires $id: ${path.relative(root, source.schemaPath)}`);
      }
      if (names.has(reference)) throw new Error(`Duplicate projected schema reference: ${reference}`);
      names.set(reference, declaration.typeName);
    }
  }
  return names;
}

function rendersDeclaration(typeName, schema, ownerSchema, namesByReference) {
  if (Array.isArray(schema.oneOf)) {
    const variants = schema.oneOf.map((variant) => rendersSchema(variant, ownerSchema, namesByReference, 1));
    return `export type ${typeName} =\n${variants.map((variant) => `  | ${variant}`).join("\n")};`;
  }
  return `export type ${typeName} = ${rendersSchema(schema, ownerSchema, namesByReference, 0)};`;
}

function rendersSchema(schema, ownerSchema, namesByReference, depth) {
  if (schema === true) return "JsonValue";
  if (schema === false) return "never";
  if (schema === null || typeof schema !== "object" || Array.isArray(schema)) {
    throw new Error("Projected JSON Schema nodes must be objects or Booleans.");
  }
  if (Object.keys(schema).length === 0) return "JsonValue";
  if (typeof schema.$ref === "string") {
    const reference = schema.$ref.startsWith("#") ? `${ownerSchema.$id}${schema.$ref}` : schema.$ref;
    const name = namesByReference.get(reference);
    if (name === undefined) throw new Error(`JSON Schema reference has no projected TypeScript name: ${reference}`);
    return name;
  }
  if (Object.hasOwn(schema, "const")) return JSON.stringify(schema.const);
  if (Array.isArray(schema.enum)) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (Array.isArray(schema.oneOf)) {
    return schema.oneOf.map((variant) => rendersSchema(variant, ownerSchema, namesByReference, depth)).join(" | ");
  }
  if (Array.isArray(schema.type)) {
    return schema.type.map((type) => rendersSchema({ ...schema, type }, ownerSchema, namesByReference, depth)).join(" | ");
  }
  switch (schema.type) {
    case "null": return "null";
    case "boolean": return "boolean";
    case "integer":
    case "number": return "number";
    case "string": return "string";
    case "array": {
      const item = rendersSchema(schema.items ?? {}, ownerSchema, namesByReference, depth);
      const wrapped = item.includes(" | ") ? `(${item})` : item;
      return `readonly ${wrapped}[]`;
    }
    case "object": return rendersObject(schema, ownerSchema, namesByReference, depth);
    default: throw new Error(`Unsupported JSON Schema type in projection: ${JSON.stringify(schema)}`);
  }
}

function rendersObject(schema, ownerSchema, namesByReference, depth) {
  const properties = schema.properties ?? {};
  const propertyNames = Object.keys(properties);
  if (propertyNames.length === 0) {
    if (schema.additionalProperties === undefined || schema.additionalProperties === true) return "JsonObject";
    if (schema.additionalProperties === false) return "Readonly<Record<string, never>>";
    return `Readonly<Record<string, ${rendersSchema(schema.additionalProperties, ownerSchema, namesByReference, depth)}>>`;
  }
  if (schema.additionalProperties !== undefined && schema.additionalProperties !== false) {
    throw new Error("Projection does not support named properties combined with additionalProperties.");
  }
  const required = new Set(schema.required ?? []);
  const indentation = "  ".repeat(depth);
  const members = propertyNames.map((name) => {
    const propertyType = rendersSchema(properties[name], ownerSchema, namesByReference, depth + 1);
    const propertyName = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
    return `${indentation}  readonly ${propertyName}${required.has(name) ? "" : "?"}: ${propertyType};`;
  });
  return `Readonly<{\n${members.join("\n")}\n${indentation}}>`;
}

function readsPointer(document, pointer) {
  if (pointer === "#") return document;
  if (!pointer.startsWith("#/")) throw new Error(`Unsupported JSON pointer: ${pointer}`);
  return pointer.slice(2).split("/").reduce((value, encoded) => {
    const segment = encoded.replaceAll("~1", "/").replaceAll("~0", "~");
    if (value === null || typeof value !== "object" || !(segment in value)) {
      throw new Error(`JSON pointer does not resolve: ${pointer}`);
    }
    return value[segment];
  }, document);
}

function projectsFile(target, content) {
  if (checkOnly) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== content) {
      throw new Error(`Projected artifact drift: ${path.relative(root, target)}`);
    }
    return;
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  if (fs.existsSync(target) && !fs.readFileSync(target, "utf8").startsWith(generatedMarker)) {
    throw new Error(`Refusing to overwrite a non-generated artifact: ${path.relative(root, target)}`);
  }
  fs.writeFileSync(target, content, "utf8");
}

function walks(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const candidate = path.join(directory, entry.name);
    return entry.isDirectory() ? walks(candidate) : [candidate];
  });
}

function readsJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function toPosix(value) {
  return value.split(path.sep).join("/");
}
