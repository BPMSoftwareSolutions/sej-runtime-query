import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const checkOnly = process.argv.includes("--check");
const descriptorName = "capability-body.projection.v1.json";
const generatedMarker = "// @generated by scripts/project-linear-capability-bodies.mjs";
const descriptors = walks(path.join(root, "capabilities"))
  .filter((file) => path.basename(file) === descriptorName)
  .sort();
const projected = [];

for (const descriptorPath of descriptors) {
  const descriptor = readsJson(descriptorPath);
  const descriptorRoot = path.dirname(descriptorPath);
  const executionModelPath = path.resolve(descriptorRoot, descriptor.sourceExecutionModel);
  const executionModel = readsJson(executionModelPath);
  validatesDescriptor(descriptor, executionModel, descriptorPath);

  const [resolveStep, executeStep, projectStep] = executionModel.steps;
  const contextImport = `../types/${descriptor.capabilityId}-context.type.js`;
  const body = [
    generatedMarker,
    `// Source: ${toPosix(path.relative(root, executionModelPath))}`,
    `import type { ${descriptor.contextTypeName} } from "${contextImport}";`,
    "",
    `export async function ${descriptor.functionName}(`,
    `  context: ${descriptor.contextTypeName},`,
    "): Promise<unknown> {",
    `  const authority = await context.edges.invokes("${resolveStep.semanticIdentity}", context);`,
    `  const execution = await context.edges.invokes("${executeStep.semanticIdentity}", authority);`,
    `  return context.edges.projects("${projectStep.semanticIdentity}", execution);`,
    "}",
    "",
  ].join("\n");

  const contextType = [
    generatedMarker,
    `import type { SemanticEdges } from "@deterministic-solutions/semantic-kernel";`,
    "",
    `export type ${descriptor.contextTypeName} = Readonly<{`,
    "  edges: SemanticEdges;",
    "  request: unknown;",
    "}>;",
    "",
  ].join("\n");

  const registrationName = `registers${toPascal(descriptor.capabilityId)}Authority`;
  const registration = [
    generatedMarker,
    "",
    `export const ${registrationName} = Object.freeze({`,
    `  capabilityId: "${descriptor.capabilityId}",`,
    `  authorityRoot: "capabilities/${descriptor.capabilityId}",`,
    `  status: "drafted",`,
    `  executionModelId: "${executionModel.executionModelId}",`,
    `  implementationDisposition: "semantic-authority-not-yet-implemented",`,
    "});",
    "",
  ].join("\n");

  const projectorMetadata = [
    generatedMarker,
    "",
    "export const projectsCapabilityBody = Object.freeze({",
    `  capabilityId: "${descriptor.capabilityId}",`,
    `  executionModelId: "${executionModel.executionModelId}",`,
    `  bodyIdentity: "${descriptor.capabilityId}",`,
    `  source: "${toPosix(path.relative(root, executionModelPath))}",`,
    `  status: "drafted",`,
    "});",
    "",
  ].join("\n");

  const projectorTypes = [
    generatedMarker,
    "",
    "export const projectsCapabilityTypes = Object.freeze({",
    `  capabilityId: "${descriptor.capabilityId}",`,
    `  contextContract: "${descriptor.capabilityId}.input.v1",`,
    `  resultContract: "${descriptor.capabilityId}.receipt.v1",`,
    `  status: "drafted",`,
    "});",
    "",
  ].join("\n");

  projectsFile(path.resolve(descriptorRoot, descriptor.targetBody), body);
  projectsFile(path.resolve(descriptorRoot, descriptor.targetContextType), contextType);
  if (descriptor.registrationProjection !== "external") {
    projectsFile(path.resolve(descriptorRoot, descriptor.targetRegistration), registration);
  }
  projectsFile(path.join(descriptorRoot, "projects-capability-body.ts"), projectorMetadata);
  projectsFile(path.join(descriptorRoot, "projects-capability-types.ts"), projectorTypes);
  projected.push(descriptor.capabilityId);
}

console.log(`PASS linear-body-projection (${projected.length} ${checkOnly ? "verified" : "projected"})`);

function validatesDescriptor(descriptor, executionModel, descriptorPath) {
  const steps = executionModel.steps;
  const expectedOperations = ["invoke", "invoke", "project"];
  const operations = Array.isArray(steps) ? steps.map((step) => step.operation) : [];
  const binds = Array.isArray(steps) ? steps.map((step) => step.binds ?? null) : [];
  const inputs = Array.isArray(steps) ? steps.map((step) => step.input) : [];
  const valid = descriptor.generatedBodyPolicy === "resolve-execute-project-return-only"
    && steps?.length === 3
    && JSON.stringify(operations) === JSON.stringify(expectedOperations)
    && JSON.stringify(binds) === JSON.stringify(["authority", "execution", null])
    && JSON.stringify(inputs) === JSON.stringify(["context", "authority", "execution"])
    && steps[2].returns === true;
  if (!valid) {
    throw new Error(`Execution model cannot project a linear body: ${path.relative(root, descriptorPath)}`);
  }
}

function projectsFile(target, content) {
  if (checkOnly) {
    if (
      !fs.existsSync(target)
      || normalizesLineEndings(fs.readFileSync(target, "utf8")) !== normalizesLineEndings(content)
    ) {
      throw new Error(`Projected artifact drift: ${path.relative(root, target)}`);
    }
    return;
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  if (fs.existsSync(target)) {
    const existing = fs.readFileSync(target, "utf8");
    if (!existing.startsWith(generatedMarker)) {
      throw new Error(`Refusing to overwrite a non-generated artifact: ${path.relative(root, target)}`);
    }
  }
  fs.writeFileSync(target, content, "utf8");
}

function normalizesLineEndings(value) {
  return value.replaceAll("\r\n", "\n");
}

function walks(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const candidate = path.join(directory, entry.name);
    return entry.isDirectory() ? walks(candidate) : [candidate];
  });
}

function readsJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function toPascal(value) {
  return value.split("-").map((part) => `${part[0].toUpperCase()}${part.slice(1)}`).join("");
}

function toPosix(value) {
  return value.split(path.sep).join("/");
}
